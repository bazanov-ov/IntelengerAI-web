#!/bin/bash
# Этот скрипт предназначен для автоматического развертывания приложения.

# `set -e` означает, что скрипт немедленно завершит работу, если какая-либо команда вернет ошибку.
set -e

echo "--- Перехожу в директорию проекта /opt/app/IntelengerAI ---"
# Переходим в директорию. Если не получилось, выводим ошибку и выходим.
cd /opt/app/IntelengerAI || { echo "Ошибка: Не удалось найти директорию /opt/app/IntelengerAI. Прерываю выполнение."; exit 1; }

echo "--- Скачиваю последние изменения из Git ---"
git pull

echo "--- Пересобираю и перезапускаю Docker контейнеры ---"
docker-compose up -d --build --force-recreate

echo "--- Развертывание app успешно завершено! ---" 
